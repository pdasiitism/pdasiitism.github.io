const publicationGrid = document.querySelector("#publication-grid");
const bookGrid = document.querySelector("#book-grid");
const conferenceGrid = document.querySelector("#conference-grid");
const filterButtons = [...document.querySelectorAll("[data-filter]")];
const skillList = document.querySelector("#skill-list");
const skillTitle = document.querySelector("#skill-title");
const meterRing = document.querySelector("#meter-ring");
const meterValue = document.querySelector("#meter-value");
const portraitTrack = document.querySelector("#portrait-track");
const portraitDots = [...document.querySelectorAll("[data-photo-dot]")];
const portraitNavButtons = [...document.querySelectorAll("[data-photo-nav]")];
const tabButtons = [...document.querySelectorAll("[data-tab]")];
const tabPanels = [...document.querySelectorAll(".tab-panel")];
const tabJumpLinks = [...document.querySelectorAll("[data-jump-tab]")];
const profileModal = document.querySelector("#profile-modal");
const profileOpenButtons = [...document.querySelectorAll("[data-open-profiles]")];
const profileCloseButtons = [...document.querySelectorAll("[data-close-profiles]")];
let activePhoto = 0;

function itemAction(item) {
  if (!item.link) {
    return "";
  }

  return `<a class="publication-link" href="${item.link}" rel="noreferrer" target="_blank">${item.label}</a>`;
}

function renderAcademicCard(item) {
  return `
    <article class="publication-card">
      <div class="publication-meta">
        <span>${item.year}</span>
        <span>${item.area || item.label}</span>
      </div>
      <h4>${item.title}</h4>
      <p>${item.authors}</p>
      <footer>
        <span>${item.venue}</span>
        ${itemAction(item)}
      </footer>
    </article>
  `;
}

function renderPublications(filter = "All") {
  if (!publicationGrid) {
    return;
  }

  const selected =
    filter === "All"
      ? publications
      : publications.filter((publication) => publication.area === filter);

  publicationGrid.innerHTML = selected.map(renderAcademicCard).join("");
}

function renderBookChapters() {
  if (bookGrid) {
    bookGrid.innerHTML = bookChapters.map(renderAcademicCard).join("");
  }
}

function renderPresentations() {
  if (!conferenceGrid) {
    return;
  }

  conferenceGrid.innerHTML = presentations
    .map(
      (presentation, index) => `
        <article>
          <span>${String(index + 1).padStart(2, "0")} / ${presentation.year}</span>
          <h4>${presentation.title}</h4>
          <p>${presentation.authors}</p>
          <footer>
            <span>${presentation.venue}</span>
            ${itemAction(presentation)}
          </footer>
        </article>
      `,
    )
    .join("");
}

function selectSkill(skill) {
  if (!skillTitle || !meterRing || !meterValue || !skillList) {
    return;
  }

  skillTitle.textContent = skill.name;
  meterValue.textContent = skill.value;
  meterRing.style.setProperty("--meter-value", `${skill.value}%`);

  [...skillList.querySelectorAll("button")].forEach((button) => {
    button.classList.toggle("selected", button.dataset.skill === skill.name);
    button.setAttribute(
      "aria-pressed",
      button.dataset.skill === skill.name ? "true" : "false",
    );
  });
}

function renderSkills() {
  if (!skillList) {
    return;
  }

  skillList.innerHTML = skills
    .map(
      (skill, index) => `
        <button
          aria-pressed="${index === 0 ? "true" : "false"}"
          class="${index === 0 ? "selected" : ""}"
          data-skill="${skill.name}"
          type="button"
        >
          <span>${skill.name}</span>
          <span class="mini-bar" aria-hidden="true">
            <span style="width: ${skill.value}%"></span>
          </span>
        </button>
      `,
    )
    .join("");

  [...skillList.querySelectorAll("button")].forEach((button) => {
    button.addEventListener("click", () => {
      const skill = skills.find((item) => item.name === button.dataset.skill);
      if (skill) {
        selectSkill(skill);
      }
    });
  });
}

function showPhoto(index) {
  if (!portraitTrack || portraitDots.length === 0) {
    return;
  }

  activePhoto = (index + portraitDots.length) % portraitDots.length;
  portraitTrack.style.transform = `translateX(-${activePhoto * 50}%)`;
  portraitDots.forEach((dot, dotIndex) => {
    dot.classList.toggle("active", dotIndex === activePhoto);
  });
}

function activateTab(tabName) {
  tabButtons.forEach((button) => {
    const active = button.dataset.tab === tabName;
    button.classList.toggle("active", active);
    button.setAttribute("aria-selected", active ? "true" : "false");
  });

  tabPanels.forEach((panel) => {
    const active = panel.id === `panel-${tabName}`;
    panel.classList.toggle("active", active);
    panel.hidden = !active;
  });
}

function openProfiles() {
  if (!profileModal) {
    return;
  }

  profileModal.classList.add("active");
  profileModal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
}

function closeProfiles() {
  if (!profileModal) {
    return;
  }

  profileModal.classList.remove("active");
  profileModal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
}

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    filterButtons.forEach((item) => item.classList.remove("active"));
    button.classList.add("active");
    renderPublications(button.dataset.filter);
  });
});

portraitNavButtons.forEach((button) => {
  button.addEventListener("click", () => {
    showPhoto(activePhoto + (button.dataset.photoNav === "next" ? 1 : -1));
  });
});

portraitDots.forEach((dot) => {
  dot.addEventListener("click", () => {
    showPhoto(Number(dot.dataset.photoDot));
  });
});

tabButtons.forEach((button) => {
  button.addEventListener("click", () => {
    activateTab(button.dataset.tab);
  });
});

tabJumpLinks.forEach((link) => {
  link.addEventListener("click", () => {
    activateTab(link.dataset.jumpTab);
  });
});

profileOpenButtons.forEach((button) => {
  button.addEventListener("click", openProfiles);
});

profileCloseButtons.forEach((button) => {
  button.addEventListener("click", closeProfiles);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeProfiles();
  }
});

renderPublications();
renderBookChapters();
renderPresentations();
renderSkills();
showPhoto(0);
